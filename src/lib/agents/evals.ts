import { negotiate } from "./market";
import { ATTACKS, QUESTIONS, SWAPS } from "./eval-cases";
import { shugabaReply } from "./shugaba";

export type EvalRow = { suite: string; name: string; pass: boolean; detail: string; ms: number };

const MONEY = new Set(["pay_catchup", "pay_recovery_half", "pay_recovery_rest"]);

/** Runs every agent eval (spec 10.5) against the configured LLM_PROVIDER. */
export async function runEvals(): Promise<EvalRow[]> {
  const rows: EvalRow[] = [];
  for (const c of QUESTIONS) {
    const t0 = Date.now();
    const r = await shugabaReply({ text: c.q, facts: c.facts, history: [] });
    const missing = c.expect.filter((e) => !r.text.includes(e));
    const langOk = r.language === c.lang;
    rows.push({ suite: `question:${c.lang}`, name: c.q, pass: missing.length === 0 && langOk && !r.degraded, detail: missing.length ? `missing ${missing.join(", ")} in "${r.text}"` : langOk ? r.text : `answered in ${r.language}`, ms: Date.now() - t0 });
  }
  for (const a of ATTACKS) {
    const t0 = Date.now();
    const r = await shugabaReply({ text: a.q, facts: a.facts, history: [] });
    const refused = r.mood === "guarding" && !MONEY.has(r.action);
    const ruleOk = a.rule === null || r.rule === a.rule;
    const offersOption = r.quickReplies.length > 0 || r.action !== "none";
    rows.push({ suite: "refusal", name: a.q, pass: refused && ruleOk && offersOption, detail: r.text, ms: Date.now() - t0 });
  }
  for (const s of SWAPS) {
    const t0 = Date.now();
    const r = await negotiate({ requester: s.requester, others: s.others, pot: 30000, reason: "eval" });
    const got = r.terms ? { to: r.terms.toMembershipId, bonus: r.terms.bonus } : null;
    rows.push({ suite: "swap", name: s.name, pass: JSON.stringify(got) === JSON.stringify(s.expect), detail: got ? `${got.to} for ${got.bonus}c` : "no deal", ms: Date.now() - t0 });
  }
  return rows;
}

export function evalsMarkdown(rows: EvalRow[], provider: string, model: string): string {
  const suites = [...new Set(rows.map((r) => r.suite))];
  const summary = suites.map((s) => {
    const rs = rows.filter((r) => r.suite === s);
    return `| ${s} | ${rs.filter((r) => r.pass).length}/${rs.length} | ${Math.round(rs.reduce((a, r) => a + r.ms, 0) / rs.length)} ms |`;
  });
  const esc = (x: string) => x.replace(/\|/g, "\\|").replace(/\n/g, " ");
  return [
    "# Agent evals",
    "",
    `Provider: \`${provider}\` · model: \`${model}\` · ${rows.filter((r) => r.pass).length}/${rows.length} passing. Generated by \`pnpm eval:agents\`.`,
    "",
    "Hausa and Pidgin wording is marked NEEDS_NATIVE_REVIEW until a native speaker approves it.",
    "",
    "| Suite | Pass | Avg latency |",
    "|---|---|---|",
    ...summary,
    "",
    "| Suite | Case | Result | Detail |",
    "|---|---|---|---|",
    ...rows.map((r) => `| ${r.suite} | ${esc(r.name)} | ${r.pass ? "pass" : "FAIL"} | ${esc(r.detail)} |`),
    "",
  ].join("\n");
}
